// ========================================
// HTMLとして安全な文字に変換
// ========================================

function escapeHtml(text){

    return String(text)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}


function addFurigana(text){

    let result = escapeHtml(text);

    // ========================================
    // ① 送り仮名付きの言葉を先に処理
    // ========================================

    const specialWords =
        Object.keys(okuriganaMap)
        .sort((a,b) => b.length - a.length);

    const savedRuby = [];

    specialWords.forEach(word => {

        if(!result.includes(word)){
            return;
        }

        const parts = okuriganaMap[word];

        let html = "";

        parts.forEach(part => {

            const surface = part[0];
            const reading = part[1];

            if(reading){

                html +=
                    "<ruby>" +
                    escapeHtml(surface) +
                    "<rt>" +
                    escapeHtml(reading) +
                    "</rt>" +
                    "</ruby>";

            }else{

                html +=
                    escapeHtml(surface);

            }

        });

        const token =
            "@@SPECIAL_" +
            savedRuby.length +
            "@@";

        savedRuby.push(html);

        result =
            result
            .split(escapeHtml(word))
            .join(token);

    });


    // ========================================
    // ② 普通の漢字語
    // ========================================

    const words =
        Object.keys(furiganaMap)
        .sort((a,b) => b.length - a.length);

    words.forEach(word => {

        // 送り仮名辞書にある語は
        // ここでは処理しない
        if(okuriganaMap[word]){
            return;
        }

        const escapedWord =
            escapeHtml(word);

        const reading =
            furiganaMap[word];

        result =
            result
            .split(escapedWord)
            .join(
                "<ruby>" +
                escapedWord +
                "<rt>" +
                escapeHtml(reading) +
                "</rt>" +
                "</ruby>"
            );

    });


    // ========================================
    // ③ 送り仮名付きのrubyを戻す
    // ========================================

    savedRuby.forEach((html,i) => {

        result =
            result.replaceAll(
                "@@SPECIAL_" +
                i +
                "@@",
                html
            );

    });


    return result;
}