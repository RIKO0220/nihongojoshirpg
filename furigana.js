// HTMLで使う文字を安全にする
function escapeHtml(text){

    return String(text)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}


// 漢字にふりがなを付ける
function addFurigana(text){

    let result =
        escapeHtml(text);

    const words =
        Object.keys(furiganaMap)
        .sort(
            (a,b) =>
                b.length - a.length
        );

    words.forEach(word => {

        const reading =
            furiganaMap[word];

        result =
            result.split(word).join(
                "<ruby>" +
                word +
                "<rt>" +
                reading +
                "</rt>" +
                "</ruby>"
            );

    });

    return result;
}