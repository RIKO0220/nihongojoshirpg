// ========================================
// HTMLエスケープ
// ========================================

function escapeHtml(text) {

    return String(text)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}


// ========================================
// 1語分のふりがなを作る
//
// 例:
//
// "飛び続ける": [
//     ["飛", "と"],
//     ["び", ""],
//     ["続", "つづ"],
//     ["ける", ""]
// ]
//
// ↓
//
// <ruby>飛<rt>と</rt></ruby>び
// <ruby>続<rt>つづ</rt></ruby>ける
// ========================================

function buildRuby(parts) {

    let html = "";

    for (const part of parts) {

        const text = part[0];
        const reading = part[1];

        // 読みがある部分だけrubyにする
        if (reading) {

            html +=
                "<ruby>" +
                escapeHtml(text) +
                "<rt>" +
                escapeHtml(reading) +
                "</rt>" +
                "</ruby>";

        } else {

            // 送り仮名・ひらがな・カタカナなど
            // 読みが空ならそのまま表示
            html += escapeHtml(text);
        }
    }

    return html;
}


// ========================================
// 長い語を先に処理する
//
// 例:
// 「飛び続ける」と「飛び」が両方あっても
// 必ず「飛び続ける」を先に使う。
// ========================================

const furiganaKeys = Object.keys(furiganaMap)
    .sort((a, b) => b.length - a.length);


// ========================================
// メイン
// addFurigana("鳥は空を飛び続ける")
//
// ↓
//
// 鳥(とり)は空(そら)を
// 飛(と)び続(つづ)ける
// ========================================

function addFurigana(input) {

    if (input === null || input === undefined) {
        return "";
    }

    const text = String(input);

    let result = "";
    let position = 0;

    // ====================================
    // 左から右へ「1回だけ」処理する
    //
    // 一度rubyにしたHTMLを
    // もう一度変換しない。
    //
    // これで以前起きていた
    // 「ふりがなが二重になる問題」
    // を防ぐ。
    // ====================================

    while (position < text.length) {

        let matchedKey = null;

        // 現在位置から始まる
        // 一番長い登録語を探す
        for (const key of furiganaKeys) {

            if (text.startsWith(key, position)) {
                matchedKey = key;
                break;
            }
        }


        // ====================================
        // 辞書に登録された語が見つかった
        // ====================================

        if (matchedKey !== null) {

            result += buildRuby(
                furiganaMap[matchedKey]
            );

            position += matchedKey.length;

            continue;
        }


        // ====================================
        // 辞書にない文字
        //
        // 勝手に読みを推測しない。
        // そのまま表示する。
        //
        // これが重要。
        // ====================================

        result += escapeHtml(text[position]);

        position++;
    }

    return result;
}


